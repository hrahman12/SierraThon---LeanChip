#!/usr/bin/env python3
"""Generate LeanVsDFM/PackageData.lean from the official Sierrathon files:
the BOM spreadsheet (verbatim rows) and the golden netlist transcribed from the schematic PDF.
    python3 -I tools/gen_package_data.py <Sierrathon_BOM.xlsx>
"""
import json, os, sys
import openpyxl
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
q = json.dumps
ws = openpyxl.load_workbook(sys.argv[1], data_only=True).active
rows = []
for r in list(ws.iter_rows(values_only=True))[1:]:
    if r[0] is None:
        continue
    refs = [x.strip() for x in str(r[1]).split(",")]
    rows.append(f"  ⟨{r[0]}, [{', '.join(q(x) for x in refs)}], {int(r[2])}, {q(str(r[3]))}, {q(str(r[4] or ''))}, {'true' if r[7] else 'false'}⟩")
nl = json.load(open(os.path.join(root, "..", "netlist", "Sierrathon.netlist.json")))
out = ["-- AUTO-GENERATED by tools/gen_package_data.py from Sierrathon_BOM.xlsx and the schematic netlist.",
       "namespace LeanVsDFM.Package", "",
       "structure BomLine where", "  line : Nat", "  refdes : List String", "  qty : Nat", "  value : String",
       "  mpn : String", "  dni : Bool", "deriving Repr", "",
       "/-- Sierrathon_BOM.xlsx, every row verbatim. -/",
       "def bom : List BomLine := [", ",\n".join(rows), "]", "",
       "/-- Every reference designator drawn on Sierrathon_Schematic.pdf. -/",
       "def schematicRefdes : List String := [" + ", ".join(q(k) for k in sorted(nl["components"])) + "]", "",
       "/-- Every pin connection on the schematic: (refdes, pin, net). -/",
       "def schematicPins : List (String × String × String) := [" + ", ".join(
           f"({q(r)}, {q(p)}, {q(e['net'] if isinstance(e, dict) else e)})"
           for r, c in sorted(nl["components"].items()) for p, e in c["pins"].items()
           if (e['net'] if isinstance(e, dict) else e)) + "]", "",
       "/-- Every net name on Sierrathon_Schematic.pdf (unnamed nets given descriptive names). -/",
       "def schematicNets : List String := [" + ", ".join(q(k) for k in nl["nets"]) + "]", "",
       "end LeanVsDFM.Package", ""]
open(os.path.join(root, "LeanVsDFM", "PackageData.lean"), "w").write("\n".join(out))
print("wrote LeanVsDFM/PackageData.lean:", len(rows), "BOM rows,", len(nl["components"]), "schematic parts")
