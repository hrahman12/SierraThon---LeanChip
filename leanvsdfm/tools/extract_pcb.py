#!/usr/bin/env python3
"""Read a .kicad_pcb with KiCad's own pcbnew API and emit LeanVsDFM/<Module>.lean:
`board` (every footprint and pad), `parts` (placement, courtyard, 3D body) and `outline`,
all in integer nanometres (KiCad's internal unit).

    python3 tools/extract_pcb.py <board.kicad_pcb> [Module.Name]
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from leancheck import ROOT, board_term  # noqa: E402


def main():
    path = sys.argv[1]
    mod = sys.argv[2] if len(sys.argv) > 2 else "PcbData"
    t = board_term(path)
    out = [f"-- AUTO-GENERATED by tools/extract_pcb.py from {os.path.basename(path)} (KiCad pcbnew API + OpenCascade bboxes).",
           "import LeanVsDFM.PcbTypes", "import LeanVsDFM.Fit3D", f"namespace LeanVsDFM.{mod}", "open LeanVsDFM.Pcb", "",
           f"def board : List Footprint := {t['fps']}", "",
           f"def parts : List LeanVsDFM.Fit3D.Part := {t['parts']}", "",
           f"def outline : List (Int × Int) := {t['outline']}", "",
           f"/-- Board thickness from the KiCad stack-up, nm. -/", f"def thicknessNm : Int := {t['thickness_nm']}", "",
           f"end LeanVsDFM.{mod}", ""]
    dst = os.path.join(ROOT, "LeanVsDFM", f"{mod}.lean")
    open(dst, "w").write("\n".join(out))
    print(f"wrote {dst}: {t['n']} footprints")


if __name__ == "__main__":
    main()
