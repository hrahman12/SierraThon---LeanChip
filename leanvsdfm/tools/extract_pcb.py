#!/usr/bin/env python3
"""Read a .kicad_pcb with KiCad's own pcbnew API and emit LeanVsDFM/PcbData.lean:
for every footprint its library identity, rotation, and every pad (number, net, position
relative to the footprint origin, size), all in integer nanometres (KiCad's internal unit).

    python3 tools/extract_pcb.py <board.kicad_pcb> [Module.Name]
"""
import json
import os
import sys

import pcbnew

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    path = sys.argv[1]
    mod = sys.argv[2] if len(sys.argv) > 2 else "PcbData"
    board = pcbnew.LoadBoard(path)
    q = json.dumps
    fps = []
    for fp in sorted(board.GetFootprints(), key=lambda f: f.GetReference()):
        o = fp.GetPosition()
        pads = []
        for p in fp.Pads():
            if not p.GetNumber():
                continue
            pos = p.GetPosition() - o
            sz = p.GetSize()
            pads.append(f"⟨{q(p.GetNumber())}, {q(p.GetNetname())}, {int(pos.x)}, {int(pos.y)}, {int(sz.x)}, {int(sz.y)}⟩")
        lib = str(fp.GetFPID().GetLibItemName())
        fps.append(f"  ⟨{q(fp.GetReference())}, {q(lib)}, {int(fp.GetOrientationDegrees())}, [{', '.join(pads)}]⟩")
    out = [f"-- AUTO-GENERATED by tools/extract_pcb.py from {os.path.basename(path)} (KiCad pcbnew API).",
           "import LeanVsDFM.PcbTypes", f"namespace LeanVsDFM.{mod}", "open LeanVsDFM.Pcb", "",
           f"def board : List Footprint := [", ",\n".join(fps), "]", "", f"end LeanVsDFM.{mod}", ""]
    dst = os.path.join(ROOT, "LeanVsDFM", f"{mod}.lean")
    open(dst, "w").write("\n".join(out))
    print(f"wrote {dst}: {len(fps)} footprints, {sum(f.count('⟨') - 1 for f in fps)} pads")


if __name__ == "__main__":
    main()
