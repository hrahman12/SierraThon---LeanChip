#!/usr/bin/env python3
"""Keys, pinned statements and signed verification records (Mode A, host side).

  python3 -I host/rhpc_trust.py gen-key <out.key>        new Ed25519 private key (keep secret!)
  python3 -I host/rhpc_trust.py header [<key>...]        write firmware/src/rhpc_trust_data.h
  python3 -I host/rhpc_trust.py sign <key> <record.json> write <record.json>.sig (hex)

Statement fingerprints pinned on the device (firmware/src/rhpc_trust_data.h):
  * RH and GRH theorems: "merkle-export-v1" over the Lean export of the published challenge
    file (host/lean_export.py): sha256(type_fp || value_fp of the Prop it names).
  * RHPC theorems: "sha256-pp-all-v1": sha256 of `#check` output with pp.all (host/lean_check_record.py).

The DEMO key is derived from a public string, so anyone can sign with it. The device labels
records signed with it "DEMO". Generate your own key for anything real.
"""
import hashlib
import json
import os
import sys

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOMAIN = b"RHPC-RECORD-v1\n"
DEMO_SEED = hashlib.sha256(b"RHProofChip DEMO key - private key is PUBLIC - never trust it").digest()


def demo_key():
    return Ed25519PrivateKey.from_private_bytes(DEMO_SEED)


def load_key(path):
    if path == "DEMO":
        return demo_key()
    raw = bytes.fromhex(open(path).read().strip())
    return Ed25519PrivateKey.from_private_bytes(raw)


def pub_bytes(k):
    return k.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)


def key_id(k):
    return pub_bytes(k)[:8].hex()


def canonical(rec):
    """The exact bytes that get signed: sorted keys, no spaces, ASCII."""
    return json.dumps(rec, sort_keys=True, separators=(",", ":"), ensure_ascii=True).encode()


def sign(k, json_bytes):
    return k.sign(DOMAIN + json_bytes)


def pinned_statements():
    audit = json.load(open(os.path.join(ROOT, "host", "out", "challenge_statement_audit.json")))
    pins = []
    pairs = [("riemannHypothesis", "RiemannHypothesis"),
             ("riemannZeta_eq_zero_re", "RiemannZetaZerosOnLine"),
             ("LFunction_ne_zero_of_half_lt_re", "DirichletLNonvanishingRightOfHalf"),
             ("LFunction_eq_zero_re", "DirichletLZerosOnLine"),
             ("LFunction_eq_zero_re_of_isPrimitive", "PrimitiveDirichletLZerosOnLine")]
    for thm, prop in pairs:
        t, p = audit[thm], audit[prop]
        assert t["kind"] == "thm" and p["kind"] == "def"
        fp = hashlib.sha256(bytes.fromhex(t["type_fingerprint"]) + bytes.fromhex(p["value_fingerprint"])).hexdigest()
        pins.append((thm, fp, "merkle-export-v1"))
    local = os.path.join(ROOT, "host", "out", "rhpc_statements.json")
    if os.path.exists(local):
        for thm, fp in json.load(open(local)).items():
            pins.append((thm, fp, "sha256-pp-all-v1"))
    return pins


def write_header(keys):
    lines = ["/* AUTO-GENERATED by host/rhpc_trust.py. Do not edit. */",
             "#ifndef RHPC_TRUST_DATA_H", "#define RHPC_TRUST_DATA_H", '#include "rhpc_record.h"', ""]
    for i, (label, k) in enumerate(keys):
        pb = pub_bytes(k)
        lines.append(f"static const uint8_t RHPC_KEY{i}[32] = {{" + ", ".join(f"0x{b:02x}" for b in pb) + "};")
    lines.append("static const rhpc_trusted_key_t RHPC_TRUSTED_KEYS[] = {")
    for i, (label, k) in enumerate(keys):
        lines.append(f'    {{"{key_id(k)}", RHPC_KEY{i}, "{label}"}},')
    lines += ["};", "#define RHPC_N_TRUSTED_KEYS (sizeof RHPC_TRUSTED_KEYS / sizeof RHPC_TRUSTED_KEYS[0])", ""]
    lines.append("static const rhpc_pinned_statement_t RHPC_PINNED[] = {")
    for thm, fp, method in pinned_statements():
        lines.append(f'    {{"{thm}", "{fp}", "{method}"}},')
    lines += ["};", "#define RHPC_N_PINNED (sizeof RHPC_PINNED / sizeof RHPC_PINNED[0])", "", "#endif", ""]
    out = os.path.join(ROOT, "firmware", "src", "rhpc_trust_data.h")
    open(out, "w").write("\n".join(lines))
    print(f"wrote {out}: {len(keys)} key(s), {len(pinned_statements())} pinned statements")


def main():
    a = sys.argv[1:]
    if len(a) == 2 and a[0] == "gen-key":
        k = Ed25519PrivateKey.generate()
        raw = k.private_bytes(serialization.Encoding.Raw, serialization.PrivateFormat.Raw,
                              serialization.NoEncryption())
        fd = os.open(a[1], os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        os.write(fd, raw.hex().encode() + b"\n")
        os.close(fd)
        print(f"key_id {key_id(k)} written to {a[1]} (keep it secret; it is gitignored under host/keys/)")
        return 0
    if a and a[0] == "header":
        keys = [("DEMO (private key is public)", demo_key())] + [(f"user:{os.path.basename(p)}", load_key(p)) for p in a[1:]]
        write_header(keys)
        return 0
    if len(a) == 3 and a[0] == "sign":
        k = load_key(a[1])
        data = open(a[2], "rb").read()
        open(a[2] + ".sig", "w").write(sign(k, data).hex() + "\n")
        print(f"signed {a[2]} with key_id {key_id(k)}")
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main())
