#!/usr/bin/env python3
"""Generate Sierrathon/Design.lean from the golden netlist + BOM spreadsheet,
so every Lean proof is about the actual design data, not a hand copy."""
import json, sys, openpyxl
from pathlib import Path
root = Path(__file__).resolve().parent
nl = json.load(open(root.parent / "netlist" / "Sierrathon.netlist.json"))
q = lambda s: json.dumps(s)
out = ["-- AUTO-GENERATED by gen_from_design.py from Sierrathon.netlist.json + Sierrathon_BOM.xlsx. Do not edit.",
       "namespace Sierrathon.Design", ""]
out.append("/-- Every net: name and its (refdes, pin) members. -/")
out.append("def nets : List (String × List (String × String)) := [")
rows = []
for n, mem in nl["nets"].items():
    ps = ", ".join(f"({q(r)}, {q(p)})" for r, pins in mem.items() for p in (pins if isinstance(pins, list) else [pins]))
    rows.append(f"  ({q(n)}, [{ps}])")
out.append(",\n".join(rows) + "]\n")
out.append("/-- RP2040 (U1) pin number -> pin name, from the schematic symbol. -/")
out.append("def u1PinNames : List (String × String) := [")
out.append(",\n".join(f"  ({q(p)}, {q(v['name'])})" for p, v in nl["components"]["U1"]["pins"].items()) + "]\n")
bom_path = sys.argv[1]
ws = openpyxl.load_workbook(bom_path, data_only=True).active
lines = []
for r in list(ws.iter_rows(values_only=True))[1:]:
    if r[0] is None: continue
    refs = [x.strip() for x in str(r[1]).split(",")]
    lines.append(f"  ⟨{r[0]}, [{', '.join(q(x) for x in refs)}], {int(r[2])}, {q(str(r[4] or ''))}⟩")
out.append("structure BomLine where\n  line : Nat\n  refdes : List String\n  qty : Nat\n  mpn : String\nderiving Repr\n")
out.append("/-- The BOM spreadsheet, verbatim. -/")
out.append("def bom : List BomLine := [\n" + ",\n".join(lines) + "]\n")
out.append("/-- Every refdes in the netlist (components). -/")
out.append("def netlistRefdes : List String := [" + ", ".join(q(k) for k in nl["components"]) + "]\n")
out.append("end Sierrathon.Design")
(root / "Sierrathon" / "Design.lean").write_text("\n".join(out) + "\n")
print("wrote Design.lean")
